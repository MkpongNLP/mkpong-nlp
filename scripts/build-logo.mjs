// Build the Mkpong logo deliverables into logo/dist/.
//
//   npm run build:logo        (node scripts/build-logo.mjs)
//   npm run build:logo -- --quiet
//
// Cross-platform / PowerShell-friendly: no shell pipelines, no bash-only tools,
// no rm/cp. Everything is driven by logo/logo.config.json so the export list can
// be trimmed without touching this file.
//
// Output:
//   logo/dist/mkpong-logo.js          single classic script, data embedded
//   logo/dist/mkpong-logo.css         the --mkpong-* custom properties
//   logo/dist/orthography-head.html   inline <head> snippet (no default flash)
//   logo/dist/svg/*.svg               static, literal-colour SVG exports
//   logo/dist/png/*.png               512 px and 1024 px
//   logo/dist/favicon.svg|.ico        single-M, orthography-independent
//   logo/dist/favicon-16|32|64.png
//   logo/dist/checks/contact-sheet.png  all 6 wordmarks

import { mkdirSync, readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { Resvg } from '@resvg/resvg-js';

const ROOT = process.cwd();
const DIST = join(ROOT, 'logo/dist');
const QUIET = process.argv.includes('--quiet');

const config = JSON.parse(readFileSync(join(ROOT, 'logo/logo.config.json'), 'utf8'));
const glyphData = JSON.parse(readFileSync(join(ROOT, 'logo/glyphs.json'), 'utf8'));
const runtimeSource = readFileSync(join(ROOT, 'logo/src/runtime.js'), 'utf8');

const log = (...args) => { if (!QUIET) console.log(...args); };

function write(relPath, contents) {
  const full = join(DIST, relPath);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, contents);
  return full;
}

function writeBuffer(relPath, buffer) {
  const full = join(DIST, relPath);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, buffer);
  return full;
}

/* ------------------------------------------------------------------ *
 * 1. runtime + css + head snippet
 * ------------------------------------------------------------------ */

const data = {
  meta: glyphData.meta,
  config,
  glyphs: glyphData.glyphs
};

const BANNER =
  '/*! mkpong-logo v1.0.0 | generated by scripts/build-logo.mjs - do not edit.\n' +
  ' *  Source: logo/src/runtime.js | Data: logo/glyphs.json + logo/logo.config.json\n' +
  ' *  Generated: ' + new Date().toISOString() + '\n' +
  ' *  Gelasio, SIL Open Font License 1.1 (see logo/fonts/OFL.txt)\n' +
  ' */\n';

const runtimeOut =
  BANNER +
  "'use strict';\n" +
  'var MKPONG_DATA = ' + JSON.stringify(data) + ';\n' +
  runtimeSource;

write('mkpong-logo.js', runtimeOut);

// CSS custom properties. Optional: the runtime already embeds these values as
// fallbacks, so pages only need this file if they want to restyle the logo.
function varLines(theme) {
  const roles = ['green', 'orange', 'white', 'wordmark', 'outline', 'background'];
  return roles
    .map(role => {
      const name = config.runtime.cssVariables[role];
      const map = (config.themes[theme] && config.themes[theme].overrides) || {};
      const value = Object.prototype.hasOwnProperty.call(map, role) ? map[role] : config.palette[role];
      const literal = ((config.themes[theme] || {}).literal || {})[role];
      const safe = /var\(|currentColor/.test(value) && literal ? literal : value;
      return `  ${name}: ${safe};`;
    })
    .join('\n');
}

const cssOut = [
  '/* Mkpong logo colours. Generated by scripts/build-logo.mjs from logo/logo.config.json.',
  '   Every value is a fallback; the runtime ships the same defaults inline. */',
  ':root {',
  varLines('color'),
  '}',
  '',
  '/* Opt-in dark theme: <mkpong-logo theme="dark"> or [data-mkpong-theme="dark"] on any ancestor. */',
  '[data-mkpong-theme="dark"] {',
  varLines('dark'),
  '}',
  '',
  '@media (prefers-color-scheme: dark) {',
  '  [data-mkpong-theme="auto"] {',
  varLines('dark').split('\n').map(l => '  ' + l).join('\n'),
  '  }',
  '}',
  '',
  '/* Mono: one ink colour, so the front M knocks out to the page background. */',
  '[data-mkpong-theme="mono"] {',
  varLines('mono'),
  '}',
  '',
  '/* Layout: the element itself must not add inline-block whitespace, and the',
  '   SVG scales to the container width by default. */',
  'mkpong-logo { display: inline-block; line-height: 0; }',
  'mkpong-logo > .mkpong-logo { display: block; width: 100%; height: auto; }',
  ''
].join('\n');

write('mkpong-logo.css', cssOut);

const headSnippet = [
  '<!-- Mkpong orthography, inline in <head>, BEFORE any stylesheet or logo.',
  '     Sets data-o / data-n on <html> from localStorage so the first paint',
  '     already shows the reader\'s preferred orthography (no flash of the default).',
  '     Keep it inline: a deferred script would paint the default first. -->',
  '<script>',
  '(function () {',
  '  try {',
  "    var saved = JSON.parse(localStorage.getItem('" + config.runtime.storageKey + "') || 'null');",
  '    var root = document.documentElement;',
  "    if (saved && saved.o) root.setAttribute('data-o', saved.o);",
  "    if (saved && saved.n) root.setAttribute('data-n', saved.n);",
  '  } catch (e) {}',
  '})();',
  '</script>',
  ''
].join('\n');

write('orthography-head.html', headSnippet);

/* ------------------------------------------------------------------ *
 * 2. static exports
 * ------------------------------------------------------------------ */

// Render SVGs with literal colours: resvg, email clients, OG-image scrapers and
// README viewers do not resolve CSS custom properties or currentColor.
function staticSvg(opts) {
  const api = globalThis.MkpongLogo;
  return api.renderLogo({
    o: opts.o,
    n: opts.n,
    layout: opts.layout,
    theme: opts.theme,
    dimensions: true,
    useVars: false,
    padding: opts.padding,
    square: opts.square,
    markStyle: opts.markStyle,
    markPaint: opts.markPaint
  });
}

function renderPng(svg, width, background) {
  const resvg = new Resvg(svg, {
    fitTo: { mode: 'width', value: width },
    background: background || undefined
  });
  return resvg.render().asPng();
}

function icoFromPngs(entries) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(entries.length, 4);
  const dir = Buffer.alloc(16 * entries.length);
  const blobs = [];
  let offset = 6 + dir.length;
  entries.forEach((entry, i) => {
    const at = i * 16;
    dir.writeUInt8(entry.size >= 256 ? 0 : entry.size, at + 0);
    dir.writeUInt8(entry.size >= 256 ? 0 : entry.size, at + 1);
    dir.writeUInt8(0, at + 2);
    dir.writeUInt8(0, at + 3);
    dir.writeUInt16LE(1, at + 4);
    dir.writeUInt16LE(32, at + 6);
    dir.writeUInt32LE(entry.buffer.length, at + 8);
    dir.writeUInt32LE(offset, at + 12);
    offset += entry.buffer.length;
    blobs.push(entry.buffer);
  });
  return Buffer.concat([header, dir, ...blobs]);
}

// --- 2a. load the freshly built runtime into this Node process --------------
// The dist file is a classic script: importing it executes the IIFE and sets
// globalThis.MkpongLogo (no exports needed).
await import(new URL('../logo/dist/mkpong-logo.js', import.meta.url).href);
if (!globalThis.MkpongLogo) throw new Error('build: runtime did not register globalThis.MkpongLogo');

if (existsSync(join(DIST, 'svg'))) rmSync(join(DIST, 'svg'), { recursive: true, force: true });
if (existsSync(join(DIST, 'png'))) rmSync(join(DIST, 'png'), { recursive: true, force: true });

const shortOf = (group, id) => config.orthography[group][id].short;
const darkBg = (config.layouts.backgrounds || {}).dark;

let svgCount = 0;
let pngCount = 0;

// --- 2b. orthography-dependent exports -------------------------------------
for (const layout of config.exports.orthographyLayouts) {
  for (const o of config.exports.o) {
    for (const n of config.exports.n) {
      for (const theme of config.exports.themes) {
        const name = `${layout}-${shortOf('o', o)}-${shortOf('n', n)}-${theme}`;
        const svg = staticSvg({ layout, o, n, theme });
        if (config.exports.formats.includes('svg')) {
          write(`svg/${name}.svg`, svg + '\n');
          svgCount++;
        }
        if (config.exports.formats.includes('png')) {
          for (const size of config.exports.pngSizes) {
            const bg = theme === 'dark' ? darkBg : undefined;
            writeBuffer(`png/${name}-${size}.png`, renderPng(svg, size, bg));
            pngCount++;
          }
        }
      }
    }
  }
}

// --- 2c. mark-only exports (no orthography) --------------------------------
for (const theme of config.exports.themes) {
  const name = `mark-${theme}`;
  const svg = staticSvg({ layout: 'mark', theme });
  if (config.exports.formats.includes('svg')) {
    write(`svg/${name}.svg`, svg + '\n');
    svgCount++;
  }
  if (config.exports.formats.includes('png')) {
    for (const size of config.exports.pngSizes) {
      const bg = theme === 'dark' ? darkBg : undefined;
      writeBuffer(`png/${name}-${size}.png`, renderPng(svg, size, bg));
      pngCount++;
    }
  }
}

log(`static exports: ${svgCount} SVG, ${pngCount} PNG`);

/* ------------------------------------------------------------------ *
 * 3. favicon: a single green M (never varies with orthography)
 * ------------------------------------------------------------------ */

const favTheme = config.exports.favicon.theme;
const faviconSvg = staticSvg({
  layout: 'mark',
  theme: favTheme,
  padding: config.exports.favicon.padding,
  square: config.exports.favicon.square === true,
  markStyle: config.exports.favicon.markStyle,
  markPaint: config.exports.favicon.paint
});
write('favicon.svg', faviconSvg + '\n');

const favSizes = config.exports.favicon.sizes;
const favPngs = favSizes.map(size => ({ size, buffer: renderPng(faviconSvg, size) }));
favPngs.forEach(p => writeBuffer(`favicon-${p.size}.png`, p.buffer));
if (config.exports.favicon.ico) writeBuffer('favicon.ico', icoFromPngs(favPngs));
log(`favicon: ${config.exports.favicon.markStyle} ${config.exports.favicon.paint} M, svg + ${favPngs.map(p => p.size + 'px').join(', ')} + ico`);

/* ------------------------------------------------------------------ *
 * 4. contact sheet: all 6 wordmarks, plus the favicon at 16/32/64
 * ------------------------------------------------------------------ */

const sheet = config.exports.contactSheet;
const cellWidth = sheet.cellWidth;
const cellHeight = 150;
const padding = 28;
const columns = 2;

function label(text, x, y, size, fill, anchor) {
  return `<text x="${x}" y="${y}" font-family="sans-serif" font-size="${size}" fill="${fill}"` +
    (anchor ? ` text-anchor="${anchor}"` : '') + `>${text}</text>`;
}

const combos = [];
for (const o of sheet.o) for (const n of sheet.n) combos.push({ o, n });

const rows = Math.ceil(combos.length / columns);
const sheetWidth = padding * 2 + columns * cellWidth;
// Full-size wordmark cells + a favicon strip at the bottom.
const footerHeight = 120;
const sheetHeight = padding * 2 + 46 + rows * cellHeight + footerHeight;

let sheetBody = '';
sheetBody += label('Mkpong wordmark — all 6 orthography combinations', padding, padding + 16, 20, '#1C4D2E');

combos.forEach((combo, i) => {
  const col = i % columns;
  const row = Math.floor(i / columns);
  const cellX = padding + col * cellWidth;
  const cellY = padding + 46 + row * cellHeight;
  const inner = globalThis.MkpongLogo.renderLogo({
    layout: 'wordmark',
    o: combo.o,
    n: combo.n,
    theme: 'color',
    useVars: false,
    padding: 0,
    dimensions: false
  });
  const vb = /viewBox="([^"]+)"/.exec(inner)[1].split(/\s+/).map(Number);
  const scale = Math.min((cellWidth - 20) / vb[2], 70 / vb[3]);
  const w = vb[2] * scale;
  const h = vb[3] * scale;
  const labelText = `${combo.o} + ${combo.n}  ·  ${shortOf('o', combo.o)}-${shortOf('n', combo.n)}`;
  sheetBody += `<g transform="translate(${cellX + 10},${cellY})">` +
    `<svg x="0" y="0" width="${w.toFixed(2)}" height="${h.toFixed(2)}" viewBox="${vb.join(' ')}" overflow="visible">` +
    inner.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '') +
    '</svg>' +
    label(labelText, 0, 92, 13, '#5E6A66') +
    '</g>';
  sheetBody += `<rect x="${cellX + 6}" y="${cellY - 4}" width="${cellWidth - 12}" height="${cellHeight - 14}" fill="none" stroke="#E2E8E5"/>`;
});

const footerY = padding + 46 + rows * cellHeight + 20;
sheetBody += label(`Favicon: a single ${config.exports.favicon.paint} M (the 3-M overlap reads as a blob at 16px) — native pixel size`, padding, footerY - 6, 14, '#1C4D2E');
let favX = padding;
favPngs.forEach((fav) => {
  // Native size on purpose: the point is to see what 16 px really looks like.
  const href = 'data:image/png;base64,' + fav.buffer.toString('base64');
  sheetBody += `<image x="${favX}" y="${footerY + 6 + (64 - fav.size)}" width="${fav.size}" height="${fav.size}" href="${href}"/>` +
    label(fav.size + 'px', favX, footerY + 86, 12, '#5E6A66');
  favX += fav.size + 24;
});

const sheetSvg =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${sheetWidth} ${sheetHeight}" width="${sheetWidth}" height="${sheetHeight}">` +
  `<rect width="${sheetWidth}" height="${sheetHeight}" fill="#FFFFFF"/>` +
  sheetBody +
  '</svg>';

writeBuffer('checks/contact-sheet.png', renderPng(sheetSvg, sheetWidth, '#FFFFFF'));
log('contact sheet: logo/dist/checks/contact-sheet.png');

/* ------------------------------------------------------------------ *
 * done
 * ------------------------------------------------------------------ */

if (!QUIET) {
  console.log('\nlogo/dist ready:');
  console.log('  mkpong-logo.js, mkpong-logo.css, orthography-head.html');
  console.log('  svg/  ' + svgCount + ' files');
  console.log('  png/  ' + pngCount + ' files');
  console.log('  favicon.svg, favicon.ico, favicon-16/32/64.png  (single green M)');
  console.log('  checks/contact-sheet.png');
}
